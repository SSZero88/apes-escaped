"""Write include/scus_api.h: prototypes of the exe's C functions, for code in the overlays.

Taken from the definitions in src/game/*.c. Struct pointers the overlays can't see become
`void *`; functions taking or returning a struct by value, K&R definitions and static ones
are left out. Usage: python tools/gen_scus_api.py
"""
import glob, re

BASIC = {'void', 's8', 'u8', 's16', 'u16', 's32', 'u32', 's64', 'u64', 'char', 'short', 'int', 'long',
         'unsigned', 'signed', 'f32', 'unsigned char', 'unsigned short', 'unsigned int', 'unsigned long',
         'signed char', 'signed short', 'signed int'}
DEF_RE = re.compile(r'^(?!static\b)([A-Za-z_][\w \*]*?[\s\*])(\w+)\(([^;{}]*)\)\s*\{', re.M)


def norm_type(t):
    """A type the overlays can use, or None."""
    t = re.sub(r'\b(const|volatile|register|struct|union)\b', ' ', t)
    t = ' '.join(t.replace('*', ' * ').split())
    stars = t.count('*')
    base = t.replace('*', '').strip()
    base = {'M2C_UNK': 's32', 'M2C_UNK8': 's8', 'M2C_UNK16': 's16'}.get(base, base)
    if base in BASIC:
        return base + (' ' + '*' * stars if stars else '')
    return 'void *' if stars else None


def proto(ret, name, params):
    r = norm_type(ret)
    if r is None:
        return None
    if params.strip() in ('', 'void'):
        return f'{r} {name}(void);'
    out = []
    for p in params.split(','):
        p = p.strip()
        if p == '...':
            out.append(p)
            continue
        m = re.match(r'(.*?)(\w+)\s*(\[\s*\w*\s*\])?$', p)
        if not m or not m.group(1).strip():
            return None  # K&R or unnamed oddity
        t = m.group(1) + ('*' if m.group(3) else '')
        n = norm_type(t)
        if n is None:
            return None
        out.append(n)
    return f'{r} {name}({", ".join(out)});'


def main():
    protos = {}
    for f in sorted(glob.glob('src/game/*.c')):
        text = open(f).read()
        for m in DEF_RE.finditer(text):
            ret, name, params = m.group(1), m.group(2), ' '.join(m.group(3).split())
            if ret.strip() in ('else', 'return', 'do') or name in protos:
                continue
            p = proto(ret, name, params)
            if p:
                protos[name] = p
    with open('include/scus_api.h', 'w', newline='') as fh:
        fh.write('/* Generated by tools/gen_scus_api.py: the exe\'s C functions, for the overlays. */\n'
                 '#ifndef SCUS_API_H\n#define SCUS_API_H\n\n')
        for name in sorted(protos):
            fh.write(protos[name] + '\n')
        fh.write('\n#endif\n')
    print(len(protos), 'prototypes')


if __name__ == '__main__':
    main()
